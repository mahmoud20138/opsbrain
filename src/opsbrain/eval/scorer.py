"""Evaluation and scoring rubrics for agent pipeline outputs."""

from __future__ import annotations

from pydantic import BaseModel, Field

from opsbrain.orchestrator.engine import PipelineResult


class EvaluationScore(BaseModel):
    """Multi-axis evaluation score for an incident response pipeline run."""

    overall_score: float = 0.0  # 0.0 to 10.0 scale
    anomaly_detection_score: float = 0.0
    root_cause_accuracy: float = 0.0
    solution_actionability: float = 0.0
    coordination_completeness: float = 0.0
    risk_awareness: float = 0.0
    feedback: list[str] = Field(default_factory=list)


class PipelineScorer:
    """Calculates quantitative quality metrics on agent outputs against rubrics."""

    def score_result(
        self,
        result: PipelineResult,
        *,
        expected_root_cause: str | None = None,
        expected_systems: list[str] | None = None,
    ) -> EvaluationScore:
        """Score an executed pipeline result against qualitative rubrics.

        Args:
            result: The executed PipelineResult from OrchestrationEngine.
            expected_root_cause: Optional ground truth substring for RCA validation.
            expected_systems: Optional list of systems expected to be identified.
        """
        feedback: list[str] = []

        # 1. Anomaly detection score
        monitor_out = result.get_output("monitor")
        anomaly_score = 5.0
        if monitor_out and monitor_out.structured_data:
            alerts = monitor_out.structured_data.get("alerts", [])
            if alerts:
                anomaly_score = 8.5
                if expected_systems:
                    found_systems = {
                        s for a in alerts for s in a.get("affected_systems", [])
                    }
                    if any(exp in found_systems for exp in expected_systems):
                        anomaly_score = 10.0
                    else:
                        feedback.append("Expected systems were not all identified by Monitor.")
            else:
                anomaly_score = 4.0
                feedback.append("No alerts generated by monitor.")
        else:
            feedback.append("Monitor agent output missing or unparsed.")

        # 2. RCA accuracy score
        rca_out = result.get_output("rca")
        rca_score = 5.0
        if rca_out and rca_out.structured_data:
            report = rca_out.structured_data.get("rca_report", {})
            root_cause = report.get("root_cause", "").lower()

            if expected_root_cause:
                expected_terms = expected_root_cause.lower().split()
                matched = sum(1 for term in expected_terms if term in root_cause)
                match_ratio = matched / max(len(expected_terms), 1)
                rca_score = 5.0 + (match_ratio * 5.0)
                if match_ratio < 0.5:
                    feedback.append(f"RCA diagnosed '{root_cause}' but expected '{expected_root_cause}'.")
            else:
                rca_score = 8.0 if report.get("evidence_chain") else 6.0
        else:
            feedback.append("RCA agent output missing or unparsed.")

        # 3. Solution actionability & risk awareness
        solver_out = result.get_output("solver")
        sol_score = 5.0
        risk_score = 5.0
        if solver_out and solver_out.structured_data:
            solutions = solver_out.structured_data.get("solutions", [])
            if solutions:
                has_steps = any(len(s.get("steps", [])) > 0 for s in solutions)
                has_rollback = any(bool(s.get("rollback_plan")) for s in solutions)

                sol_score = 8.0 if has_steps else 4.0
                risk_score = 9.0 if has_rollback else 5.0

                if not has_rollback:
                    feedback.append("Solutions lacked explicit rollback plans.")
            else:
                feedback.append("No solutions proposed by Solver.")
        else:
            feedback.append("Solver output missing.")

        # 4. Coordination completeness
        coord_out = result.get_output("coordinator")
        coord_score = 5.0
        if coord_out and coord_out.structured_data:
            plan = coord_out.structured_data.get("resolution_plan", {})
            action_items = plan.get("action_items", [])
            has_comms = bool(plan.get("communication_draft"))

            if action_items and has_comms:
                coord_score = 9.5
            elif action_items or has_comms:
                coord_score = 7.5
            else:
                coord_score = 4.0
                feedback.append("Resolution plan incomplete.")
        else:
            coord_score = 5.0

        overall = (
            anomaly_score * 0.20
            + rca_score * 0.30
            + sol_score * 0.25
            + coord_score * 0.15
            + risk_score * 0.10
        )

        return EvaluationScore(
            overall_score=round(overall, 2),
            anomaly_detection_score=round(anomaly_score, 2),
            root_cause_accuracy=round(rca_score, 2),
            solution_actionability=round(sol_score, 2),
            coordination_completeness=round(coord_score, 2),
            risk_awareness=round(risk_score, 2),
            feedback=feedback,
        )
